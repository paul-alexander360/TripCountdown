    fun render(kind: String, width: Int): Bitmap {
        val h = width * 3 / 4
        val bmp = Bitmap.createBitmap(width, h, Bitmap.Config.ARGB_8888)
        val canvas = Canvas(bmp)
        val k = width / 1200f
        canvas.scale(k, k)
        draw(canvas, data[kind] ?: "")
        return bmp
    }

    /** Saves a picture as a normal photo file so it works everywhere a chosen photo does. */
    fun save(ctx: Context, kind: String): String? {
        return try {
            val bmp = render(kind, 1200)
            val dir = File(ctx.filesDir, "photos").apply { mkdirs() }
            val dest = File(dir, UUID.randomUUID().toString() + ".jpg")
            dest.outputStream().use { bmp.compress(Bitmap.CompressFormat.JPEG, 92, it) }
            dest.absolutePath
        } catch (e: Exception) {
            null
        }
    }

    private fun draw(canvas: Canvas, spec: String) {
        val fill = Paint(Paint.ANTI_ALIAS_FLAG).apply { style = Paint.Style.FILL }
        val stroke = Paint(Paint.ANTI_ALIAS_FLAG).apply {
            style = Paint.Style.STROKE
            strokeCap = Paint.Cap.ROUND
            strokeJoin = Paint.Join.ROUND
        }
        val text = Paint(Paint.ANTI_ALIAS_FLAG).apply {
            textAlign = Paint.Align.CENTER
            typeface = Typeface.DEFAULT_BOLD
        }
        for (raw in spec.lines()) {
            val line = raw.trim()
            if (line.isEmpty()) continue
            val p = line.split(",")
            when (p[0]) {
                "R" -> {
                    fill.color = Color.parseColor(p[5])
                    canvas.drawRect(p[1].toFloat(), p[2].toFloat(), p[3].toFloat(), p[4].toFloat(), fill)
                }
                "RR" -> {
                    fill.color = Color.parseColor(p[6])
                    val r = p[5].toFloat()
                    canvas.drawRoundRect(RectF(p[1].toFloat(), p[2].toFloat(), p[3].toFloat(), p[4].toFloat()), r, r, fill)
                }
                "C" -> {
                    fill.color = Color.parseColor(p[4])
                    canvas.drawCircle(p[1].toFloat(), p[2].toFloat(), p[3].toFloat(), fill)
                }
                "E" -> {
                    fill.color = Color.parseColor(p[5])
                    canvas.drawOval(RectF(p[1].toFloat(), p[2].toFloat(), p[3].toFloat(), p[4].toFloat()), fill)
                }
                "P" -> {
                    fill.color = Color.parseColor(p[1])
                    val path = Path()
                    path.moveTo(p[2].toFloat(), p[3].toFloat())
                    var i = 4
                    while (i + 1 < p.size) {
                        path.lineTo(p[i].toFloat(), p[i + 1].toFloat())
                        i += 2
                    }
                    path.close()
                    canvas.drawPath(path, fill)
                }
                "L" -> {
                    stroke.color = Color.parseColor(p[6])
                    stroke.strokeWidth = p[5].toFloat()
                    canvas.drawLine(p[1].toFloat(), p[2].toFloat(), p[3].toFloat(), p[4].toFloat(), stroke)
                }
                "PL" -> {
                    stroke.strokeWidth = p[1].toFloat()
                    stroke.color = Color.parseColor(p[2])
                    val path = Path()
                    path.moveTo(p[3].toFloat(), p[4].toFloat())
                    var i = 5
                    while (i + 1 < p.size) {
                        path.lineTo(p[i].toFloat(), p[i + 1].toFloat())
                        i += 2
                    }
                    canvas.drawPath(path, stroke)
                }
                "T" -> {
                    text.color = Color.parseColor(p[4])
                    text.textSize = p[3].toFloat()
                    canvas.drawText(p[5], p[1].toFloat(), p[2].toFloat(), text)
                }
            }
        }
    }

