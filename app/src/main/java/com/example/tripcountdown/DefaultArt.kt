@Composable
fun DefaultImagePicker(kinds: List<String>, onPick: (String) -> Unit) {
    Column(verticalArrangement = Arrangement.spacedBy(6.dp)) {
        Text("Or choose a default image", style = MaterialTheme.typography.bodyMedium)
        Row(
            Modifier
                .fillMaxWidth()
                .horizontalScroll(rememberScrollState())
                .padding(horizontal = 4.dp, vertical = 8.dp),
            horizontalArrangement = Arrangement.spacedBy(12.dp)
        ) {
            kinds.forEach { kind ->
                val thumb = remember(kind) { DefaultArt.render(kind, 360).asImageBitmap() }
                Column(Modifier.width(110.dp).clickable { onPick(kind) }) {
                    Image(
                        thumb,
                        contentDescription = kind,
                        contentScale = ContentScale.Crop,
                        modifier = Modifier
                            .fillMaxWidth()
                            .height(82.dp)
                            .shadow(
                                6.dp,
                                RoundedCornerShape(10.dp),
                                ambientColor = androidx.compose.ui.graphics.Color.Black,
                                spotColor = androidx.compose.ui.graphics.Color.Black
                            )
                    )
                    Text(kind, style = MaterialTheme.typography.bodySmall, maxLines = 1, modifier = Modifier.padding(top = 4.dp))
                }
            }
        }
    }
